  private ensureTodoDrivenAutoLoop(sessionId: string, workspaceDir?: string): void {
    const todoState = this.getSessionTodoProtocolState(sessionId, workspaceDir);
    const ref: ContextRef = { scope: 'session', namespace: sessionId };
    const meta = this.getContextNamespaceMetaSafe(ref);
    const controller = autoLoopManager.getOrCreate(sessionId, meta?.autoLoopConfig);
    const currentConfig = this.getAutoLoopConfigSafe(controller);
    const ralphEnabled = currentConfig.ralphEnabled ?? (currentConfig.mode === 'ralph' ? currentConfig.enabled : false);

    if (currentConfig.pendingPlanConfirmation === true) {
      const pendingConfig: AutoLoopConfig = {
        ...currentConfig,
        enabled: false,
        mode: 'todo',
        ralphEnabled,
        pendingPlanConfirmation: true,
      };
      this.updateAutoLoopConfigSafe(controller, pendingConfig);
      if (this.getAutoLoopStateSafe(controller).isRunning) {
        this.stopAutoLoopSafe(controller, 'user_stop');
      }
      this.updateContextNamespaceMetaSafe(ref, {
        autoLoopConfig: pendingConfig,
      });
      return;
    }

    if (!todoState.hasUnfinished) {
      const nextConfig: AutoLoopConfig = {
        ...currentConfig,
        enabled: ralphEnabled,
        mode: 'ralph',
        ralphEnabled,
        pendingPlanConfirmation: false,
        pausedByUser: false,
      };
      this.updateAutoLoopConfigSafe(controller, nextConfig);
      if (this.getAutoLoopStateSafe(controller).isRunning && currentConfig.mode === 'todo') {
        this.stopAutoLoopSafe(controller, 'user_stop');
      }
      this.updateContextNamespaceMetaSafe(ref, {
        autoLoopConfig: nextConfig,
      });
      return;
    }

    if (currentConfig.pausedByUser === true) {
      const pausedConfig: AutoLoopConfig = {
        ...currentConfig,
        enabled: false,
        mode: 'todo',
        ralphEnabled,
        pendingPlanConfirmation: false,
      };
      this.updateAutoLoopConfigSafe(controller, pausedConfig);
      if (this.getAutoLoopStateSafe(controller).isRunning) {
        this.stopAutoLoopSafe(controller, 'user_stop');
      }
      this.updateContextNamespaceMetaSafe(ref, {
        autoLoopConfig: pausedConfig,
      });
      return;
    }

    const nextConfig: AutoLoopConfig = {
      ...currentConfig,
      enabled: true,
      mode: 'todo',
      ralphEnabled,
      pendingPlanConfirmation: false,
      pausedByUser: false,
    };
    this.updateAutoLoopConfigSafe(controller, nextConfig);
    this.updateContextNamespaceMetaSafe(ref, {
      autoLoopConfig: nextConfig,
    });
  }

