  private validateRequestedLlmSelection(
    requestSelection: SessionLlmSelectionInput | undefined
  ): { ok: true } | { ok: false; error: string } {
    if (!requestSelection) {
      return { ok: true };
    }
    if (
      requestSelection.reasoningPreset !== undefined &&
      requestSelection.reasoningPreset !== 'off' &&
      requestSelection.reasoningPreset !== 'low' &&
      requestSelection.reasoningPreset !== 'medium' &&
      requestSelection.reasoningPreset !== 'high'
    ) {
      return { ok: false, error: 'Invalid reasoningPreset in llmSelection.' };
    }
    if (
      requestSelection.profileId !== undefined &&
      !findResolvedLlmProfile(this.agent.getConfig(), requestSelection.profileId)
    ) {
      return { ok: false, error: `Unknown llmSelection.profileId: ${requestSelection.profileId}` };
    }
    return { ok: true };
  }

