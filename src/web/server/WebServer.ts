  private resolveAgentRuntimeLlmSelection(
    baseSelection: SessionLlmSelection,
    overrides?: import('../../types.js').AgentRuntimeOverrides
  ): { ok: true; selection: SessionLlmSelection } | { ok: false; error: string } {
    const overrideModel = String(overrides?.llmModel ?? '').trim();
    if (!overrides?.llmProfileId && !overrideModel && !overrides?.reasoningPreset) {
      return { ok: true, selection: baseSelection };
    }
    const profileId = String(overrides?.llmProfileId ?? baseSelection.profileId).trim();
    if (!findResolvedLlmProfile(this.agent.getConfig(), profileId)) {
      return { ok: false, error: `agent_llm_profile_invalid: ${profileId}` };
    }
    return {
      ok: true,
        selection: resolveSessionLlmSelection(this.agent.getConfig(), {
          ...baseSelection,
          profileId,
          model: overrideModel || (overrides?.llmProfileId ? '' : baseSelection.model),
          reasoningPreset: overrides?.reasoningPreset ?? baseSelection.reasoningPreset,
        }),
      };
  }

  private resolveAutomationAgentRuntime(job: AutomationJob): {
    llmSelection: SessionLlmSelection;
    llmRuntime: ResolvedLlmRuntimeConfig;
    agentRuntimeOverrides?: import('../../types.js').AgentRuntimeOverrides;
    agentName?: string;
    effectiveAgentName: string;
    fallbackReason?: string;
  } {
    const baseSelection = resolveSessionLlmSelection(this.agent.getConfig(), job.llmSelection);
    const requestedAgentName = String(job.agentName ?? '').trim();
    let agentRuntimeOverrides: import('../../types.js').AgentRuntimeOverrides | undefined;
    let effectiveAgentName = 'default';
    let fallbackReason: string | undefined;
    if (requestedAgentName) {
      this.refreshGlobalAgentCatalog();
      const profile = this.findGlobalAgentProfile(requestedAgentName);
      if (profile) {
        agentRuntimeOverrides = toAgentRuntimeOverrides(profile);
        effectiveAgentName = profile.name;
      } else {
        fallbackReason = `agent_not_found:${requestedAgentName}`;
      }
    }
    const agentSelection = this.resolveAgentRuntimeLlmSelection(baseSelection, agentRuntimeOverrides);
    if (!agentSelection.ok) {
      throw new Error(agentSelection.error);
    }
    return {
      llmSelection: agentSelection.selection,
      llmRuntime: resolveLlmRuntimeConfig(this.agent.getConfig(), agentSelection.selection),
      ...(agentRuntimeOverrides ? { agentRuntimeOverrides } : {}),
      ...(requestedAgentName ? { agentName: requestedAgentName } : {}),
      effectiveAgentName,
      ...(fallbackReason ? { fallbackReason } : {}),
    };
  }

  private handleStopAutoLoopMessage(ws: WebSocket, request: StopAutoLoopRequest): void {
    const context = this.resolveStopAutoLoopContext(request);
    if (!context) {
      return;
    }
    if (!this.canWebSocketAccessContext(ws, context)) {
      this.emitToClient(ws, {
        type: 'server_error',
        data: { error: 'share_scope_forbidden' },
      });
      return;
    }
    if (this.isObserveOnlyActiveRun(context) || !this.canControlWebActiveRun(ws, context)) {
      this.emitControlConflict(ws, context);
      return;
    }
    this.stopAutoLoopForContext(context, ws);
  }

