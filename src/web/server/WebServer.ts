  private stopAutoLoopForContext(context: ContextRef, ws?: WebSocket): void {
    const key = makeAutoLoopKey(context);
    const controller = autoLoopManager.get(key);
    if (context.scope === 'session') {
      const meta = this.getContextNamespaceMetaSafe(context);
      const currentConfig = {
        ...this.getAutoLoopConfigSafe(controller),
        ...meta?.autoLoopConfig,
      };
      const nextConfig: AutoLoopConfig = {
        ...DEFAULT_AUTO_LOOP_CONFIG,
        ...currentConfig,
        enabled: false,
        ralphEnabled:
          currentConfig.mode === 'ralph'
            ? false
            : currentConfig.ralphEnabled ?? false,
        pausedByUser: true,
      };
      this.updateContextNamespaceMetaSafe(context, {
        autoLoopConfig: nextConfig,
      });
      this.updateAutoLoopConfigSafe(controller, nextConfig);
    }
    if (controller) {
      this.stopAutoLoopSafe(controller, 'user_stop');
      this.emitToClient(
        ws,
        {
        type: 'auto_loop_stopped',
        data: {
          context,
          reason: 'User stopped auto loop',
          totalRounds: this.getAutoLoopStateSafe(controller).currentRound,
        },
      }
      );
    }
  }

