  private emitRunEvent(ownerWs: WebSocket | undefined, context: ContextRef, message: WSMessage): void {
    const sent = new Set<WebSocket>();
    if (ownerWs && this.canWebSocketAccessContext(ownerWs, context)) {
      sent.add(ownerWs);
      const ownerMessage = this.messageForSocket(ownerWs, context, message);
      if (ownerMessage) {
        this.emitToClient(ownerWs, ownerMessage);
      }
    }
    for (const client of this.wss?.clients ?? []) {
      if (sent.has(client)) {
        continue;
      }
      if (!this.canWebSocketAccessContext(client, context)) {
        continue;
      }
      const clientMessage = this.messageForSocket(client, context, message);
      if (clientMessage) {
        this.emitToClient(client, clientMessage);
      }
    }
    webServerLogger.debug(
      `[WebServer] Run event emitted type=${message.type} context=${context.scope}:${context.namespace} clients=${this.wss?.clients?.size ?? 0}`
    );
  }

