  private resolveWorkspaceDirForContext(context: ContextRef): string {
    const meta = this.getContextNamespaceMetaSafe(context);
    const workspaceFromMeta = String(meta?.workspaceDir ?? '').trim();
    if (workspaceFromMeta) {
      return workspaceFromMeta;
    }
    const contextAgent = this.resolveAgentForContext(context);
    const artifactWorkspaceDir = String(contextAgent.getInterruptedArtifact?.(context)?.workspaceDir ?? '').trim();
    if (artifactWorkspaceDir) {
      return artifactWorkspaceDir;
    }
    if (context.scope === 'session') {
      const runtimeWorkspaceDir = String(this.sessionRuntimes?.get(context.namespace)?.workspaceDir ?? '').trim();
      if (runtimeWorkspaceDir) {
        return runtimeWorkspaceDir;
      }
    }
    return this.agent?.getConfig().agent.workspaceDir ?? './workspace';
  }

  private resolveWorkspaceDirForRun(context: ContextRef, requestedWorkspaceDir?: string): string {
    const existingWorkspaceDir = this.resolveWorkspaceDirForContext(context);
    const normalizedRequested = String(requestedWorkspaceDir ?? '').trim();
    const hasExistingWorkspace = existingWorkspaceDir.trim().length > 0;
    const hasRequestedWorkspace = normalizedRequested.length > 0;
    const hasStoredMetaWorkspace =
      String(this.getContextNamespaceMetaSafe(context)?.workspaceDir ?? '').trim().length > 0;

    // Keep session workspace stable once established; only use request value for brand-new session contexts.
    if (context.scope === 'session' && hasStoredMetaWorkspace) {
      return existingWorkspaceDir;
    }
    if (hasRequestedWorkspace) {
      return normalizedRequested;
    }
    if (hasExistingWorkspace) {
      return existingWorkspaceDir;
    }
    return this.agent.getConfig().agent.workspaceDir;
  }

