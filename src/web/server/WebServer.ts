  private messageForSocket(ws: WebSocket, context: ContextRef, message: WSMessage): WSMessage | null {
    const scope = this.getWebSocketScopeMap().get(ws);
    if (scope?.mode === 'shared_ls' && scope.transportMode === 'text') {
      return this.textProtocolMessageForSocket(scope, context, message);
    }
    const data = message.data;
    if (!data || typeof data !== 'object' || Array.isArray(data)) {
      return message;
    }
    const nextData = {
      ...(data as Record<string, unknown>),
    };
    if ('interactionState' in nextData) {
      nextData.interactionState = this.resolveInteractionStateForSocket(ws, context);
    }
    if (nextData.activeRun && typeof nextData.activeRun === 'object' && !Array.isArray(nextData.activeRun)) {
      nextData.activeRun = {
        ...(nextData.activeRun as Record<string, unknown>),
        interactionState: this.resolveInteractionStateForSocket(ws, context),
      };
    }
    return {
      ...message,
      data: nextData,
    };
  }

