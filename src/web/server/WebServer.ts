  private async cleanupSessionRuntime(
    sessionId: string,
    options?: { cancelActive?: boolean; cancelReason?: string }
  ): Promise<void> {
    const runtime = this.sessionRuntimes.get(sessionId);
    if (!runtime) {
      return;
    }
    const context: ContextRef = {
      scope: 'session',
      namespace: sessionId,
    };
    const hasActiveRun = this.hasActiveRunForContext(context);
    if (hasActiveRun && options?.cancelActive === false) {
      runtime.configDirty = true;
      webServerLogger.info(`[WebServer] Deferred session runtime cleanup while run is active: session=${sessionId}`);
      return;
    }
    if (hasActiveRun || options?.cancelActive !== false) {
      runtime.agent.cancelContext(context);
    }
    this.rejectPendingPlanInputByContext(context, options?.cancelReason ?? 'run_canceled');
    this.stopAutoLoopForContext(context);
    this.removeTrackedRunsForContext(context);
    runtime.cleanupPromise ??= runtime.agent.cleanup().finally(() => {
      runtime.cleanupPromise = undefined;
    });
    await runtime.cleanupPromise;
    if (this.sessionRuntimes.get(sessionId) === runtime) {
      this.sessionRuntimes.delete(sessionId);
    }
  }

  private async invalidateSessionRuntimes(options?: { cancelActive?: boolean; cancelReason?: string }): Promise<void> {
    const sessionIds = [...this.sessionRuntimes.keys()];
    for (const sessionId of sessionIds) {
      await this.cleanupSessionRuntime(sessionId, options);
    }
  }

  private async cleanupRootRuntimeAfterConfigChangeIfIdle(): Promise<void> {
    if (this.hasActiveRootAgentRun()) {
      this.rootRuntimeConfigDirty = true;
      return;
    }
    if (this.rootRuntimeCleanupPromise) {
      await this.rootRuntimeCleanupPromise;
      return;
    }
    this.rootRuntimeConfigDirty = true;
    const cleanupPromise = this.agent.cleanup().finally(() => {
      if (this.rootRuntimeCleanupPromise === cleanupPromise) {
        this.rootRuntimeCleanupPromise = undefined;
      }
    });
    this.rootRuntimeCleanupPromise = cleanupPromise;
    await cleanupPromise;
    this.rootRuntimeConfigDirty = false;
  }

