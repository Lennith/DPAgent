  constructor(config: WebServerConfig) {
    this.port = config.port;
    this.configPath = config.configPath;
    this.server.keepAliveTimeout = 5000;
    this.server.headersTimeout = 10000;
    this.server.requestTimeout = 300000;
    this.server.on('connection', (socket) => {
      this.httpConnections.add(socket);
      socket.on('close', () => {
        this.httpConnections.delete(socket);
      });
    });
    this.eventLoopDelay.enable();
    const allowMissingApiKeyAtBoot = !!config.allowMissingApiKeyAtBoot;
    const configManager = new ConfigManager();

    if (!fs.existsSync(this.configPath)) {
      throw new Error(`config.yaml not found: ${this.configPath}`);
    }
    configManager.loadFromYaml(this.configPath);

    const loadedConfig = configManager.get();
    webServerLogger.info(`Using config source: ${this.configPath}`);
    webServerLogger.info(`Skills directory: ${loadedConfig.agent.skillsDir ?? '(not configured)'}`);

    let loadedRuntime: ReturnType<typeof resolveLlmRuntimeConfig> | undefined;
    try {
      loadedRuntime = resolveLlmRuntimeConfig(loadedConfig);
    } catch (error) {
      if (!allowMissingApiKeyAtBoot || !(error instanceof Error) || error.message !== LLM_PROFILE_NOT_CONFIGURED_ERROR) {
        throw error;
      }
    }
    const rawApiKey = String(loadedRuntime?.apiKey ?? '').trim();
    const hasValidApiKey = rawApiKey.length >= 20;
    this.bootMissingApiKey = !loadedRuntime || !hasValidApiKey;
    if (this.bootMissingApiKey && allowMissingApiKeyAtBoot && loadedRuntime) {
      const defaultProfileId = loadedConfig.llmProfiles.defaultProfileId;
      const bootConfig: AgentConfig = {
        ...loadedConfig,
        llmProfiles: {
          ...loadedConfig.llmProfiles,
          profiles: loadedConfig.llmProfiles.profiles.map((profile) =>
            profile.id === defaultProfileId ? { ...profile, apiKey: BOOT_PLACEHOLDER_API_KEY } : profile
          ),
        },
      };
      this.agent = new DPAgent({
        config: bootConfig,
        allowMissingApiKeyAtBoot: true,
      });
      webServerLogger.warn(
        'API key is missing at boot. Web server starts in setup mode; chat requests will be blocked until API key is configured.'
      );
    } else if (this.bootMissingApiKey && allowMissingApiKeyAtBoot) {
      this.agent = new DPAgent({
        config: loadedConfig,
        allowMissingApiKeyAtBoot: true,
      });
      webServerLogger.warn(
        'LLM profile is missing at boot. Web server starts in setup mode; chat requests will be blocked until a provider profile is configured.'
      );
    } else {
      this.agent = new DPAgent({
        config: loadedConfig,
      });
    }
    this.wss = new WebSocketServer({
      server: this.server,
      verifyClient: (info, done) => {
        const share = this.resolveShareRequestAccess(info.req);
        const allowed =
          isSameOriginRequest(info.req) &&
          (isAuthenticatedForRemoteAccess(info.req, this.getRemoteAccessAuthConfig()) || share !== null);
        done(allowed, allowed ? undefined : 401, allowed ? undefined : 'Authentication required');
      },
    });
    this.refreshGlobalAgentCatalog();
    const runtimeDataDir =
      String(this.agent.getConfig().agent.runtimeDataDir ?? '').trim() ||
      path.join(process.cwd(), 'runtime');
    this.downloadLinkService = new DownloadLinkService({
      runtimeDataDir,
      publicBaseUrl: this.resolveDownloadPublicBaseUrl(this.agent.getConfig()),
      ttlMs: this.agent.getConfig().web?.downloadLinkTtlMs,
    });
    this.installDownloadLinkIssuer(this.agent);
    this.automationStore = this.agent.getAutomationStore();
    this.agent.initHooks(this.agent.getConfig().agent.workspaceDir || 'process.cwd()');
    this.autoGeneratedSkillGovernanceService = new AutoGeneratedSkillGovernanceService({
      skillWriteStore: this.agent.getSkillWriteStore(),
      getWorkspaceToolsetName: (workspaceDir) =>
        this.agent.resolveToolsetName({
          scope: 'workspace',
          namespace: workspaceDir || this.agent.getConfig().agent.workspaceDir,
        }),
      getLlmClient: async () => {
        await this.agent.initialize();
        return this.agent.getLLMClient();
      },
      reloadSkills: () => this.agent.reloadSkills(),
      publishWorkspaceGeneratedPack: (workspaceDir) =>
        this.agent.republishAutoGeneratedWorkspaceSkills(workspaceDir),
      logger: {
        warn: (message) => webServerLogger.warn(message),
        info: (message) => webServerLogger.info(message),
      },
    });
    this.automationExecutionService = new AutomationExecutionService({
      store: this.automationStore,
      ensureSessionRuntime: this.ensureSessionRuntime.bind(this),
      cleanupSessionRuntime: this.cleanupSessionRuntime.bind(this),
      trackActiveRun: (runId, context) => this.reserveTrackedRun(runId, context, undefined, 'automation'),
      updateContextNamespaceMetaSafe: (context, updates) => {
        this.updateContextNamespaceMetaSafe(context, updates);
        return this.getContextNamespaceMetaSafe(context) ?? null;
      },
      getDefaultWorkspaceDir: () => this.agent.getConfig().agent.workspaceDir,
      getContextMessages: (context) => this.resolveAgentForContext(context).getContextMessages(context),
      mutateWorkspaceMemory: (input) =>
        this.agent.mutateMemory({
          action: 'add',
          scope: 'workspace',
          title: input.title,
          content: input.content,
          workspaceDir: input.workspaceDir,
          sessionId: input.sessionId,
          reason: input.reason,
        }),
      resolveAutomationAgentRuntime: (job) => this.resolveAutomationAgentRuntime(job),
      logger: {
        warn: (message) => webServerLogger.warn(message),
      },
    });
    this.automationScheduler = new AutomationScheduler({
      store: this.automationStore,
      executeJob: async (job, triggerAt, options) => {
        await this.automationExecutionService.executeJob(job, triggerAt, options);
      },
      logger: {
        warn: (message) => webServerLogger.warn(message),
      },
    });
    this.automationRoutes = new AutomationRoutes({
      store: this.automationStore,
      executionService: this.automationExecutionService,
      getDefaultWorkspaceDir: () => this.agent.getConfig().agent.workspaceDir,
      getConfig: () => this.agent.getConfig(),
    });

    this.setupRoutes();
    this.setupWebSocket();
  }

